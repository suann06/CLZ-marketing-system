import { ApplicationStatus, LaunchStatus, LeadStatus } from "@prisma/client";
import { prisma } from "@/server/db/client";
import { compareCampaigns, summarizeCampaignFunnel, type CampaignComparisonEntry } from "@/server/services/feedback-service";

// Phase 4E: composes the already-existing Stage 10/Stage 11 aggregation
// (compareCampaigns(), which itself reuses getCampaignPerformance() per
// campaign — see feedback-service.ts) with a small number of new,
// deterministic, read-only queries that genuinely don't exist anywhere
// else in the codebase yet: the three "Attention Required" conditions and
// a recent-ActivityLog read. Nothing here writes, nothing here duplicates
// a calculation that already exists elsewhere.

export type DashboardKpis = {
  totalLeads: number;
  totalApplications: number;
  wonSales: number;
  totalSalesValue: string;
  winRate: number;
};

// `rate` is the conversion rate from the PREVIOUS stage into this one —
// absent for the first stage, and deliberately null (not 0) for Clicks
// (Ads -> Clicks has no rate: this system never captures ad-impression/
// reach data, so a click-through rate can't be legitimately computed —
// same reasoning as campaign-performance-service.ts's own
// FunnelConversionRates). Populated from summarizeCampaignFunnel()'s own
// already-computed rate fields — never a new calculation.
export type FunnelStage = { key: string; label: string; count: number; rate?: number | null };

export type AttentionItem = {
  id: string;
  message: string;
  href: string;
};

export type RecentActivityItem = {
  id: string;
  label: string;
  contextLabel: string;
  contextHref: string | null;
  actorType: string;
  createdAt: string;
};

export type DashboardOverview = {
  kpis: DashboardKpis;
  funnel: FunnelStage[];
  campaigns: CampaignComparisonEntry[];
  attention: {
    zeroClickCampaigns: AttentionItem[];
    hotLeadsWithoutHandover: AttentionItem[];
    submittedWithoutSale: AttentionItem[];
  };
  recentActivity: RecentActivityItem[];
};

const RECENT_ACTIVITY_LIMIT = 20;
const ATTENTION_LIMIT = 8;

// "Launched" means an actual live Launch row (LaunchStatus.live) — not
// merely a Launch existing (pending/launching/failed/cancelled rows don't
// count as "launched"). Cross-referenced against totalClicks already
// computed per campaign by compareCampaigns() — no extra click query.
async function getZeroClickLiveCampaigns(campaigns: CampaignComparisonEntry[]): Promise<AttentionItem[]> {
  const liveLaunches = await prisma.launch.findMany({
    where: { status: LaunchStatus.live },
    select: { campaignId: true },
    distinct: ["campaignId"],
  });
  const liveCampaignIds = new Set(liveLaunches.map((l) => l.campaignId));

  return campaigns
    .filter((c) => liveCampaignIds.has(c.campaignId) && c.totalClicks === 0)
    .slice(0, ATTENTION_LIMIT)
    .map((c) => ({
      id: c.campaignId,
      message: `"${c.campaignName}" is live but has recorded zero clicks.`,
      href: `/campaigns/${c.campaignId}/performance`,
    }));
}

async function getHotLeadsWithoutHandover(): Promise<AttentionItem[]> {
  const leads = await prisma.lead.findMany({
    where: { status: LeadStatus.hot, handoverAt: null },
    include: { campaign: { select: { name: true } } },
    orderBy: { updatedAt: "desc" },
    take: ATTENTION_LIMIT,
  });

  return leads.map((lead) => ({
    id: lead.id,
    message: `${lead.name || lead.phone} (${lead.campaign.name}) is hot but hasn't been handed over.`,
    href: `/leads/${lead.id}`,
  }));
}

async function getSubmittedWithoutSale(): Promise<AttentionItem[]> {
  const leads = await prisma.lead.findMany({
    where: { applicationStatus: ApplicationStatus.submitted, sale: null },
    include: { campaign: { select: { name: true } } },
    orderBy: { updatedAt: "desc" },
    take: ATTENTION_LIMIT,
  });

  return leads.map((lead) => ({
    id: lead.id,
    message: `${lead.name || lead.phone} (${lead.campaign.name}) submitted an application with no sale outcome yet.`,
    href: `/leads/${lead.id}`,
  }));
}

