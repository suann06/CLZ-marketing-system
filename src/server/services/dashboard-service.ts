// Resolves entityId -> a real name only for the two entity types that have
// one worth showing (campaign name, lead name/phone) — a genuine lookup
// against the id already stored on the row, never a guess. Every other
// entityType falls back to its humanized type label with no link, rather
// than fabricating a name.
async function buildRecentActivity(): Promise<RecentActivityItem[]> {
  const rows = await prisma.activityLog.findMany({
    orderBy: { createdAt: "desc" },
    take: RECENT_ACTIVITY_LIMIT,
  });

  const campaignIds = [...new Set(rows.filter((r) => r.entityType === "campaign").map((r) => r.entityId))];
  const leadIds = [...new Set(rows.filter((r) => r.entityType === "lead").map((r) => r.entityId))];

  const [campaigns, leads] = await Promise.all([
    campaignIds.length > 0
      ? prisma.campaign.findMany({ where: { id: { in: campaignIds } }, select: { id: true, name: true } })
      : Promise.resolve([]),
    leadIds.length > 0
      ? prisma.lead.findMany({ where: { id: { in: leadIds } }, select: { id: true, name: true, phone: true } })
      : Promise.resolve([]),
  ]);
  const campaignById = new Map(campaigns.map((c) => [c.id, c]));
  const leadById = new Map(leads.map((l) => [l.id, l]));

  return rows.map((row) => {
    let contextLabel = ENTITY_LABELS[row.entityType] ?? row.entityType.replace(/_/g, " ");
    let contextHref: string | null = null;

    if (row.entityType === "campaign") {
      const campaign = campaignById.get(row.entityId);
      if (campaign) {
        contextLabel = campaign.name;
        contextHref = `/campaigns/${campaign.id}/brief`;
      }
    } else if (row.entityType === "lead") {
      const lead = leadById.get(row.entityId);
      if (lead) {
        contextLabel = lead.name || lead.phone;
        contextHref = `/leads/${lead.id}`;
      }
    }

    return {
      id: row.id,
      label: ACTIVITY_LABELS[row.action] ?? row.action.replace(/_/g, " "),
      contextLabel,
      contextHref,
      actorType: row.actorType,
      createdAt: row.createdAt.toISOString(),
    };
  });
}

export async function getDashboardOverview(): Promise<DashboardOverview> {
  const { campaigns } = await compareCampaigns();
  const totals = summarizeCampaignFunnel(campaigns);

  const kpis: DashboardKpis = {
    totalLeads: totals.totalLeads,
    totalApplications: totals.totalApplications,
    wonSales: totals.wonSales,
    totalSalesValue: totals.totalSalesValue,
    winRate: totals.winRate,
  };

  const funnel: FunnelStage[] = [
    { key: "ads", label: "Ads", count: totals.totalAds },
    { key: "clicks", label: "Clicks", count: totals.totalClicks, rate: null },
    { key: "enquiries", label: "WhatsApp Enquiries", count: totals.totalWhatsAppEnquiries, rate: totals.clickToEnquiryRate },
    { key: "applications", label: "Applications", count: totals.totalApplications, rate: totals.enquiryToApplicationRate },
    { key: "qualified", label: "Qualified", count: totals.totalQualifiedLeads, rate: totals.applicationToQualifiedRate },
    { key: "sales", label: "Sales", count: totals.totalSales, rate: totals.qualifiedToSaleRate },
  ];

  const [zeroClickCampaigns, hotLeadsWithoutHandover, submittedWithoutSale, recentActivity] = await Promise.all([
    getZeroClickLiveCampaigns(campaigns),
    getHotLeadsWithoutHandover(),
    getSubmittedWithoutSale(),
    buildRecentActivity(),
  ]);

  return {
    kpis,
    funnel,
    campaigns,
    attention: { zeroClickCampaigns, hotLeadsWithoutHandover, submittedWithoutSale },
    recentActivity,
  };
}
